"""
ZFinance Reconciliation — Evaluation Script
=============================================
Runs the agent against synthetic data and scores it against
the ground truth mismatch log generated by data/generate.py.

This is your honest metrics layer — exactly what Razorpay will look for.

Run:
    python tests/eval.py
"""

import csv
import json
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from agent.reconciler import ReconciliationAgent


LEDGER_PATH      = "data/ledger.csv"
BANK_PATH        = "data/bank_statement.csv"
GROUND_TRUTH     = "data/mismatch_ground_truth.csv"


def load_ground_truth() -> dict[str, str]:
    """Load the mismatch log produced by generate.py."""
    gt = {}
    with open(GROUND_TRUTH) as f:
        for row in csv.DictReader(f):
            gt[row["ledger_ref"].upper()] = row["type"]
    return gt


def run_eval():
    print("\n" + "═" * 60)
    print("  ZFinance Reconciliation — Evaluation")
    print("═" * 60)

    ground_truth = load_ground_truth()
    print(f"\nGround truth mismatches: {len(ground_truth)}")
    for t, refs in _group_by_type(ground_truth).items():
        print(f"  {t:<30} {len(refs)} records")

    print("\nRunning reconciliation agent...")
    agent  = ReconciliationAgent()
    report = agent.run(LEDGER_PATH, BANK_PATH)

    print(report.summary())

    # ── Precision / recall on exception detection ─────────────────────────────
    print("\n" + "─" * 60)
    print("  EXCEPTION DETECTION ACCURACY")
    print("─" * 60)

    predicted_exceptions = {e.ledger_ref.upper() for e in report.exceptions}
    actual_exceptions    = set(ground_truth.keys())

    true_pos  = predicted_exceptions & actual_exceptions
    false_pos = predicted_exceptions - actual_exceptions   # flagged but was actually clean
    false_neg = actual_exceptions - predicted_exceptions   # missed a real exception

    precision = len(true_pos) / len(predicted_exceptions) if predicted_exceptions else 0
    recall    = len(true_pos) / len(actual_exceptions)    if actual_exceptions    else 0
    f1        = (2 * precision * recall / (precision + recall)
                 if (precision + recall) else 0)

    print(f"  True positives  (correct exceptions)  : {len(true_pos)}")
    print(f"  False positives (wrongly flagged)      : {len(false_pos)}")
    print(f"  False negatives (missed exceptions)    : {len(false_neg)}")
    print(f"\n  Precision  : {precision:.2%}")
    print(f"  Recall     : {recall:.2%}")
    print(f"  F1 score   : {f1:.2%}")

    # ── Exception type classification accuracy ────────────────────────────────
    print("\n" + "─" * 60)
    print("  EXCEPTION TYPE CLASSIFICATION")
    print("─" * 60)

    correct_type = 0
    for exc in report.exceptions:
        ref = exc.ledger_ref.upper()
        if ref in ground_truth:
            predicted = exc.exception_type
            actual    = ground_truth[ref]
            match     = "✓" if _types_match(predicted, actual) else "✗"
            print(f"  {match} {ref:<12} predicted={predicted:<20} actual={actual}")
            if _types_match(predicted, actual):
                correct_type += 1

    if report.exceptions:
        type_acc = correct_type / len([e for e in report.exceptions
                                       if e.ledger_ref.upper() in ground_truth])
        print(f"\n  Type classification accuracy: {type_acc:.2%}")

    # ── Save full results ─────────────────────────────────────────────────────
    out = {
        "match_rate":           round(report.match_rate(), 4),
        "exact_matches":        len(report.exact_matches),
        "fuzzy_matches":        len(report.fuzzy_matches),
        "exceptions":           len(report.exceptions),
        "exception_precision":  round(precision, 4),
        "exception_recall":     round(recall, 4),
        "exception_f1":         round(f1, 4),
        "details":              report.to_dict(),
    }
    with open("tests/eval_results.json", "w") as f:
        json.dump(out, f, indent=2, default=str)

    print(f"\n  Full results saved to tests/eval_results.json")
    print("═" * 60 + "\n")


def _group_by_type(gt: dict) -> dict:
    groups: dict[str, list] = {}
    for ref, typ in gt.items():
        groups.setdefault(typ, []).append(ref)
    return groups


def _types_match(predicted: str, actual: str) -> bool:
    """Fuzzy match on exception type names — LLM may use slightly different labels."""
    mapping = {
        "missing_from_bank":  ["missing", "missing_from_bank", "not_found"],
        "amount_discrepancy": ["amount_diff", "amount_discrepancy", "fee", "rounding"],
        "date_shift":         ["date_diff", "date_shift", "settlement_delay", "timing_diff"],
        "description_mismatch": ["ref_mismatch", "description_mismatch", "desc_mismatch"],
        "split_transaction":  ["split_transaction", "split_unresolved", "split"],
        "bank_duplicate":     ["duplicate", "bank_duplicate", "double_entry"],
    }
    for canonical, variants in mapping.items():
        if actual in variants or actual == canonical:
            return predicted in variants or predicted == canonical
    return predicted == actual


if __name__ == "__main__":
    run_eval()
